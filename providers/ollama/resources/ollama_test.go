func TestClassifyAuthProbe(t *testing.T) {
	tests := []struct {
		name    string
		code    int
		open    []int
		want    bool
		wantErr bool
	}{
		// A refusal for lack of credentials means that path is gated, whether
		// the instance or a proxy in front of it did the refusing.
		{"read 401", http.StatusUnauthorized, readOpenStatuses, true, false},
		{"read 403", http.StatusForbidden, readOpenStatuses, true, false},
		{"read 407", http.StatusProxyAuthRequired, readOpenStatuses, true, false},
		{"write 401", http.StatusUnauthorized, writeOpenStatuses, true, false},
		{"write 403", http.StatusForbidden, writeOpenStatuses, true, false},
		{"write 407", http.StatusProxyAuthRequired, writeOpenStatuses, true, false},

		// A served read, and a write turned away only for its unparseable body.
		{"read 200", http.StatusOK, readOpenStatuses, false, false},
		{"write 400", http.StatusBadRequest, writeOpenStatuses, false, false},
		{"write 422", http.StatusUnprocessableEntity, writeOpenStatuses, false, false},

		// A 400 says nothing about reads, and a 200 to an unparseable create
		// body is not an Ollama create handler answering.
		{"read 400", http.StatusBadRequest, readOpenStatuses, false, true},
		{"write 200", http.StatusOK, writeOpenStatuses, false, true},

		// An endpoint that is not served, a login redirect, and a gateway
		// failure are all "could not tell", never a posture claim.
		{"404", http.StatusNotFound, writeOpenStatuses, false, true},
		{"405", http.StatusMethodNotAllowed, writeOpenStatuses, false, true},
		{"302", http.StatusFound, readOpenStatuses, false, true},
		{"500", http.StatusInternalServerError, writeOpenStatuses, false, true},
		{"502", http.StatusBadGateway, readOpenStatuses, false, true},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := classifyAuthProbe(tt.code, tt.open, "write")
			if tt.wantErr {
				assert.Error(t, err, "an unclassifiable answer must not be reported as a posture finding")
				assert.False(t, got)
				return
			}
			assert.NoError(t, err)
			assert.Equal(t, tt.want, got)
		})
	}
}

func TestWriteOpenStatusesDoNotOverlapAuthRequired(t *testing.T) {
	for _, code := range writeOpenStatuses {
		assert.NotContains(t, authRequiredStatuses, code,
			"a status cannot mean both that writes are gated and that they are open")
	}
	for _, code := range readOpenStatuses {
		assert.NotContains(t, authRequiredStatuses, code)
	}
}

// The executor resolves the fields of one resource concurrently, so two
// Show-backed accessors on the same model enter fetchShow at the same time.
// fetchShow keeps a lock-free fast path, which means its flag is read outside
// the mutex and written under it: with a plain bool that is a data race, and
// this test reports it as one under -race.
//
// The call count is the second half. The re-check inside the lock is what keeps
// a burst of accessors down to a single /api/show call, and dropping it would
// leave this green under -race while costing one request per field.
func TestFetchShowIsSafeUnderConcurrentAccessors(t *testing.T) {
	var calls atomic.Int32
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		calls.Add(1)
		assert.Equal(t, "/api/show", r.URL.Path)
		_ = json.NewEncoder(w).Encode(api.ShowResponse{
			License:    "  MIT  ",
			Modelfile:  "FROM llama3.1:latest\nADAPTER /opt/lora/a.gguf\n",
			System:     "You are a helpful assistant.",
			Template:   "{{ .System }}",
			Parameters: "  stop \"<|eot_id|>\"  ",
			Renderer:   "harmony",
			Parser:     "qwen3-coder",
		})
	}))
	defer srv.Close()

	conn, err := connection.NewOllamaConnection(1, &inventory.Asset{}, &inventory.Config{
		Options: map[string]string{connection.HostOption: srv.URL},
	})
	require.NoError(t, err)

	model := &mqlOllamaModel{MqlRuntime: &plugin.Runtime{Connection: conn}}
	model.Name = plugin.TValue[string]{Data: "llama3.1:latest", State: plugin.StateIsSet}

	accessors := []struct {
		field string
		read  func() (string, error)
		want  string
	}{
		{"license", model.license, "MIT"},
		{"modelfile", model.modelfile, "FROM llama3.1:latest\nADAPTER /opt/lora/a.gguf\n"},
		{"system", model.system, "You are a helpful assistant."},
		{"template", model.template, "{{ .System }}"},
		{"parameters", model.parameters, `stop "<|eot_id|>"`},
		{"renderer", model.renderer, "harmony"},
		{"parser", model.parser, "qwen3-coder"},
	}

	got := make([]string, len(accessors))
	errs := make([]error, len(accessors))
	start := make(chan struct{})
	var wg sync.WaitGroup
	for i, a := range accessors {
		wg.Add(1)
		go func() {
			defer wg.Done()
			<-start
			got[i], errs[i] = a.read()
		}()
	}
	close(start)
	wg.Wait()

	for i, a := range accessors {
		require.NoError(t, errs[i], a.field)
		// Each accessor must return its own field of the Show answer. A
		// crossed pair, renderer reading show.Parser, fails here.
		assert.Equal(t, a.want, got[i], a.field)
	}

	assert.Equal(t, int32(1), calls.Load(),
		"every Show-backed field on one model must share a single /api/show call")
}

func TestClassifyCorsProbe(t *testing.T) {
	const probe = "https://0123456789abcdef.example.com"

	tests := []struct {
		name        string
		allowOrigin string
		observed    bool
		want        bool
		wantKnown   bool
	}{
		// OLLAMA_ORIGINS=* turns the allowlist into every origin, and
		// gin-contrib/cors then names `*` rather than the caller's origin.
		{"every origin", "*", true, true, true},

		// A wildcard pattern that happens to cover the unrelated origin is
		// echoed back instead. Same exposure, different wire form.
		{"unrelated origin echoed back", probe, true, true, true},
		{"echo differing only in case", strings.ToUpper(probe), true, true, true},

		// The stock allowlist: the instance answers cross-origin requests and
		// allows this one nothing.
		{"refused with no origin named", "", true, false, true},
		{"another origin named", "http://localhost", true, false, true},

		// Nothing on the instance handles cross-origin requests, so it has said
		// nothing about them. A false here would pass a check the instance
		// never earned.
		{"no cross-origin handling anywhere", "", false, false, false},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, known := classifyCorsProbe(tt.allowOrigin, probe, tt.observed)
			assert.Equal(t, tt.wantKnown, known)
			assert.Equal(t, tt.want, got)
		})
	}

	t.Run("an empty probe origin never matches an empty allowance", func(t *testing.T) {
		got, known := classifyCorsProbe("", "", true)
		assert.True(t, known)
		assert.False(t, got, "no origin asked about and none allowed is not permission for every origin")
	})
}

func TestClassifyForeignHostProbe(t *testing.T) {
	tests := []struct {
		name          string
		controlStatus int
		foreignStatus int
		want          bool
		wantErr       bool
	}{
		// The instance serves its own host name and refuses the unrelated one.
		{"refused", http.StatusOK, http.StatusForbidden, true, false},
		// It serves both, so a page that points a domain it controls at this
		// address is answered.
		{"served", http.StatusOK, http.StatusOK, false, false},

		// The control was not served, so whatever turned it away would have
		// turned the other away too and the pair proves nothing. A 403 control
		// is the case that matters: crediting that refusal to the host name
		// would report a gated instance as protected.
		{"gated control", http.StatusUnauthorized, http.StatusUnauthorized, false, true},
		{"forbidden control", http.StatusForbidden, http.StatusForbidden, false, true},
		{"failing control", http.StatusBadGateway, http.StatusForbidden, false, true},
		{"redirected control", http.StatusFound, http.StatusForbidden, false, true},

		// The control was served but the answer to the unrelated name is
		// neither of the two that mean anything.
		{"unreadable answer", http.StatusOK, http.StatusBadGateway, false, true},
		{"redirected answer", http.StatusOK, http.StatusFound, false, true},
		{"not found", http.StatusOK, http.StatusNotFound, false, true},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := classifyForeignHostProbe(tt.controlStatus, tt.foreignStatus)
			if tt.wantErr {
				assert.Error(t, err, "an unreadable pair must not be reported as a posture finding")
				assert.False(t, got)
				return
			}
			assert.NoError(t, err)
			assert.Equal(t, tt.want, got)
		})
	}
}
