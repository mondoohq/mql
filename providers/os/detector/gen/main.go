// Command gen builds the embedded Yocto Project release codename set the
// detector uses to recognize a Yocto / OpenEmbedded image.
//
// The Yocto Project names each release with a codename (dunfell, scarthgap,
// ...). A Yocto image's os-release carries that codename as VERSION_CODENAME,
// and because the words are Yocto-coined they do not collide with any other
// distribution's codenames -- so the set is a reliable Yocto marker. It needs a
// new entry for every Yocto release, which is what this generator automates.
//
// The release list is read from endoflife.date, which tracks every Yocto cycle
// and its codename as machine-readable JSON:
// https://endoflife.date/api/yocto.json
//
// Usage:
//
//	go run ./gen -out ../yocto_releases.gen.go              # fetch the list
//	go run ./gen -in yocto.json -out ../yocto_releases.gen.go  # from a file
//
// The -in form reads a file a caller already downloaded and validated (the
// update-yocto-releases workflow does this), so the fetch and the generation
// are separable and the download can be checked before it is trusted.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"regexp"
	"sort"
	"strings"
	"time"
)

const sourceURL = "https://endoflife.date/api/yocto.json"

// minCodenames guards against a truncated or error response regenerating a
// near-empty set that would stop recognizing Yocto images. endoflife.date has
// tracked well over a dozen Yocto releases for years; a handful means the
// source did not return the release list.
const minCodenames = 8

// codenamePattern is what a real Yocto codename looks like: a single lowercase
// word. Anything else (an empty codename, a date, punctuation) is skipped
// rather than written into the set.
var codenamePattern = regexp.MustCompile(`^[a-z]+$`)

type release struct {
	Cycle    string `json:"cycle"`
	Codename string `json:"codename"`
}

func main() {
	inPath := flag.String("in", "", "path to a downloaded yocto.json; fetched from endoflife.date when empty")
	outPath := flag.String("out", "yocto_releases.gen.go", "path to write the generated Go file to")
	flag.Parse()

	raw, err := load(*inPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}

	var releases []release
	if err := json.Unmarshal(raw, &releases); err != nil {
		fmt.Fprintln(os.Stderr, "gen: parse yocto release list:", err)
		os.Exit(1)
	}

	// Collect the distinct, lowercased codenames.
	set := map[string]bool{}
	for _, r := range releases {
		name := strings.ToLower(strings.TrimSpace(r.Codename))
		if codenamePattern.MatchString(name) {
			set[name] = true
		}
	}
	if len(set) < minCodenames {
		fmt.Fprintf(os.Stderr, "gen: only %d codenames parsed from %s, expected at least %d -- refusing to regenerate\n",
			len(set), sourceURL, minCodenames)
		os.Exit(1)
	}
	names := make([]string, 0, len(set))
	for name := range set {
		names = append(names, name)
	}
	sort.Strings(names)

	src, err := render(names)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen: format:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*outPath, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen: write:", err)
		os.Exit(1)
	}
	fmt.Printf("wrote %d Yocto codenames to %s\n", len(names), *outPath)
}

// load returns the raw JSON from the file at path, or from endoflife.date when
// path is empty.
func load(path string) ([]byte, error) {
	if path != "" {
		return os.ReadFile(path)
	}
	client := &http.Client{Timeout: 60 * time.Second}
	resp, err := client.Get(sourceURL)
	if err != nil {
		return nil, fmt.Errorf("fetch %s: %w", sourceURL, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("fetch %s: status %s", sourceURL, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

func render(names []string) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Copyright Mondoo, Inc. 2024, 2026\n")
	b.WriteString("// SPDX-License-Identifier: BUSL-1.1\n\n")
	b.WriteString("// Code generated by \"go run ./gen\"; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Source: %s\n", sourceURL)
	// No timestamp in the file on purpose: it must be byte-identical across runs
	// when the release list did not change, so the update-yocto-releases workflow
	// opens a pull request only when a codename actually appeared. The fetch date
	// goes in the pull request body instead.
	b.WriteString("// Regenerated by the update-yocto-releases workflow.\n\n")
	b.WriteString("package detector\n\n")
	b.WriteString("// yoctoReleaseCodenames is the set of Yocto Project release codenames, keyed\n")
	b.WriteString("// lowercase. A Yocto / OpenEmbedded image's os-release VERSION_CODENAME is one\n")
	b.WriteString("// of these; the yocto resolver uses it to recognize a Yocto image even when the\n")
	b.WriteString("// image ships a custom DISTRO with its own os-release ID.\n")
	b.WriteString("var yoctoReleaseCodenames = map[string]bool{\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\t%q: true,\n", name)
	}
	b.WriteString("}\n")
	return format.Source([]byte(b.String()))
}
