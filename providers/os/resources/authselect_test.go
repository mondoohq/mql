const authselectPreamble = "# Generated by authselect\n" +
	"# Do not modify this file manually, use authselect instead. Any user changes will be overwritten.\n" +
	"# You can stop authselect from managing your configuration by calling 'authselect opt-out'.\n" +
	"# See authselect(8) for more details.\n\n"

// writeAuthselectHost lays out a system on which authselect selected the
// fixture profile with the with-lock feature: the profile, the files
// authselect generated from it (as `authselect test` 1.2.6 and 1.5.0 print
// them), and the links to them. It returns the root directory.
func writeAuthselectHost(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	write := func(p, content string, mode os.FileMode) {
		full := filepath.Join(root, p)
		require.NoError(t, os.MkdirAll(filepath.Dir(full), 0o755))
		require.NoError(t, os.WriteFile(full, []byte(content), mode))
		require.NoError(t, os.Chmod(full, mode))
	}
	testdata := func(elem ...string) string {
		data, err := os.ReadFile(filepath.Join(append([]string{"authselect", "testdata"}, elem...)...))
		require.NoError(t, err)
		return string(data)
	}

	write("/etc/authselect/authselect.conf", "custom/fixture\nwith-lock\n", 0o644)
	for _, name := range []string{"README", "system-auth", "postlogin"} {
		write("/etc/authselect/custom/fixture/"+name, testdata("profile", name), 0o644)
	}
	for _, tmpl := range authselectTemplates {
		content := authselectPreamble
		switch tmpl.name {
		case "system-auth", "postlogin":
			content += testdata("generated", "01."+tmpl.name)
		}
		write("/etc/authselect/"+tmpl.name, content, 0o644)
		require.NoError(t, os.MkdirAll(filepath.Join(root, filepath.Dir(tmpl.link)), 0o755))
		require.NoError(t, os.Symlink("/etc/authselect/"+tmpl.name, filepath.Join(root, tmpl.link)))
	}
	return root
}

func newAuthselect(t *testing.T, root string) *mqlAuthselect {
	t.Helper()
	rt := memFSRuntime(t, afero.NewBasePathFs(afero.NewOsFs(), root))
	res, err := CreateResource(rt, "authselect", map[string]*llx.RawData{})
	require.NoError(t, err)
	return res.(*mqlAuthselect)
}

func authselectTemplateNamed(t *testing.T, a *mqlAuthselect, name string) *mqlAuthselectTemplate {
	t.Helper()
	templates := a.GetTemplates()
	require.NoError(t, templates.Error)
	for _, r := range templates.Data {
		if tmpl := r.(*mqlAuthselectTemplate); tmpl.Name.Data == name {
			return tmpl
		}
	}
	t.Fatalf("no template %s", name)
	return nil
}

func TestAuthselectNotConfigured(t *testing.T) {
	a := newAuthselect(t, t.TempDir())

	configured := a.GetConfigured()
	require.NoError(t, configured.Error)
	assert.False(t, configured.Data)

	assert.True(t, a.GetProfileId().IsNull())
	assert.True(t, a.GetIsCustom().IsNull())
	assert.True(t, a.GetFeatures().IsNull())
	assert.True(t, a.GetProfileDir().IsNull())
	assert.True(t, a.GetTemplates().IsNull())
	assert.True(t, a.GetIntact().IsNull())
}

func TestAuthselectEmptyConfigIsNotConfigured(t *testing.T) {
	root := t.TempDir()
	require.NoError(t, os.MkdirAll(filepath.Join(root, "etc/authselect"), 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(root, "etc/authselect/authselect.conf"), []byte("\n"), 0o644))
	a := newAuthselect(t, root)

	configured := a.GetConfigured()
	require.NoError(t, configured.Error)
	assert.False(t, configured.Data)
	assert.True(t, a.GetProfileId().IsNull())
}

func TestAuthselectProfile(t *testing.T) {
	a := newAuthselect(t, writeAuthselectHost(t))

	assert.True(t, a.GetConfigured().Data)
	assert.Equal(t, "custom/fixture", a.GetProfileId().Data)
	assert.True(t, a.GetIsCustom().Data)
	assert.Equal(t, []any{"with-lock"}, a.GetFeatures().Data)
	dir := a.GetProfileDir()
	require.NoError(t, dir.Error)
	assert.Equal(t, "/etc/authselect/custom/fixture", dir.Data.Path.Data)

	templates := a.GetTemplates()
	require.NoError(t, templates.Error)
	names := []string{}
	for _, r := range templates.Data {
		names = append(names, r.(*mqlAuthselectTemplate).Name.Data)
	}
	assert.Equal(t, []string{"system-auth", "password-auth", "fingerprint-auth", "smartcard-auth", "postlogin", "nsswitch.conf", "dconf-db", "dconf-locks"}, names)

	intact := a.GetIntact()
	require.NoError(t, intact.Error)
	assert.True(t, intact.Data)
}

func TestAuthselectTemplate(t *testing.T) {
	a := newAuthselect(t, writeAuthselectHost(t))
	sys := authselectTemplateNamed(t, a, "system-auth")

	assert.Equal(t, "/etc/authselect/custom/fixture/system-auth", sys.GetFile().Data.Path.Data)
	assert.Equal(t, "/etc/authselect/system-auth", sys.GetGeneratedFile().Data.Path.Data)

	content := sys.GetContent()
	require.NoError(t, content.Error)
	assert.Contains(t, content.Data, "auth        required      pam_faillock.so preauth silent\n")
	assert.NotContains(t, content.Data, "{")

	entries := sys.GetEntries()
	require.NoError(t, entries.Error)
	type faillock struct {
		pamType string
		line    int64
		options []any
	}
	var got []faillock
	for _, r := range entries.Data {
		e := r.(*mqlPamConfServiceEntry)
		assert.Equal(t, "/etc/authselect/custom/fixture/system-auth", e.Service.Data)
		if e.Module.Data == "pam_faillock.so" {
			got = append(got, faillock{e.PamType.Data, e.LineNumber.Data, e.Options.Data})
		}
	}
	// zero-based lines of the template, not of the generated file
	assert.Equal(t, []faillock{
		{"auth", 2, []any{"preauth", "silent"}},
		{"auth", 6, []any{"authfail"}},
		{"account", 13, []any{}},
	}, got)

	// a template the profile does not ship generates an empty file
	nss := authselectTemplateNamed(t, a, "nsswitch.conf")
	assert.False(t, nss.GetFile().Data.GetExists().Data)
	assert.Equal(t, "", nss.GetContent().Data)
	assert.Empty(t, nss.GetEntries().Data)
	assert.True(t, nss.GetIntact().Data)
}

func TestAuthselectTemplateEntriesDoNotCollideWithPamConf(t *testing.T) {
	a := newAuthselect(t, writeAuthselectHost(t))
	sys := authselectTemplateNamed(t, a, "system-auth")
	require.NoError(t, sys.GetEntries().Error)

	// pam.conf reads the template as written, operators included
	res, err := NewResource(a.MqlRuntime, "pam.conf", map[string]*llx.RawData{
		"path": llx.StringData("/etc/authselect/custom/fixture/system-auth"),
	})
	require.NoError(t, err)
	entries := res.(*mqlPamConf).GetEntries()
	require.NoError(t, entries.Error)
	raw := entries.Data["/etc/authselect/custom/fixture/system-auth"].([]any)
	var preauth *mqlPamConfServiceEntry
	for _, r := range raw {
		if e := r.(*mqlPamConfServiceEntry); e.LineNumber.Data == 2 {
			preauth = e
		}
	}
	require.NotNil(t, preauth)
	assert.Contains(t, preauth.Options.Data, `{include`)
}

func TestAuthselectNotIntact(t *testing.T) {
	tests := []struct {
		name   string
		change func(t *testing.T, root string)
	}{
		{"line appended to the generated file", func(t *testing.T, root string) {
			f, err := os.OpenFile(filepath.Join(root, "etc/authselect/system-auth"), os.O_APPEND|os.O_WRONLY, 0)
			require.NoError(t, err)
			_, err = f.WriteString("auth        sufficient    pam_permit.so\n")
			require.NoError(t, err)
			require.NoError(t, f.Close())
		}},
		{"generated file replaced the link", func(t *testing.T, root string) {
			link := filepath.Join(root, "etc/pam.d/password-auth")
			require.NoError(t, os.Remove(link))
			data, err := os.ReadFile(filepath.Join(root, "etc/authselect/password-auth"))
			require.NoError(t, err)
			require.NoError(t, os.WriteFile(link, data, 0o644))
		}},
		{"link to another file", func(t *testing.T, root string) {
			link := filepath.Join(root, "etc/nsswitch.conf")
			require.NoError(t, os.Remove(link))
			require.NoError(t, os.Symlink("/etc/authselect/user-nsswitch.conf", link))
		}},
		{"generated file mode", func(t *testing.T, root string) {
			require.NoError(t, os.Chmod(filepath.Join(root, "etc/authselect/postlogin"), 0o600))
		}},
		{"generated file missing", func(t *testing.T, root string) {
			require.NoError(t, os.Remove(filepath.Join(root, "etc/authselect/dconf-db")))
		}},
		{"template changed after the files were generated", func(t *testing.T, root string) {
			f, err := os.OpenFile(filepath.Join(root, "etc/authselect/custom/fixture/system-auth"), os.O_APPEND|os.O_WRONLY, 0)
			require.NoError(t, err)
			_, err = f.WriteString("session     required      pam_echo.so added\n")
			require.NoError(t, err)
			require.NoError(t, f.Close())
		}},
		{"feature enabled without applying it", func(t *testing.T, root string) {
			require.NoError(t, os.WriteFile(filepath.Join(root, "etc/authselect/authselect.conf"), []byte("custom/fixture\nwith-lock\nwithout-nullok\n"), 0o644))
		}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := writeAuthselectHost(t)
			tt.change(t, root)
			intact := newAuthselect(t, root).GetIntact()
			require.NoError(t, intact.Error)
			assert.False(t, intact.Data)
		})
	}
}

// On RHEL 8 and 9, authselect appends the maps of user-nsswitch.conf the
// profile does not set to the nsswitch.conf it generates.
func TestAuthselectUserNsswitch(t *testing.T) {
	setup := func(t *testing.T) string {
		root := writeAuthselectHost(t)
		copyTestdata := func(dst string, elem ...string) {
			data, err := os.ReadFile(filepath.Join(append([]string{"authselect", "testdata"}, elem...)...))
			require.NoError(t, err)
			require.NoError(t, os.WriteFile(filepath.Join(root, dst), data, 0o644))
		}
		require.NoError(t, os.WriteFile(filepath.Join(root, "etc/authselect/authselect.conf"), []byte("custom/fixture\nwith-lock\nwith-sss\n"), 0o644))
		copyTestdata("etc/authselect/custom/fixture/nsswitch.conf", "profile", "nsswitch.conf")
		copyTestdata("etc/authselect/user-nsswitch.conf", "user-nsswitch.conf")
		copyTestdata("etc/authselect/nsswitch.conf", "generated", "nsswitch.with-sss")
		return root
	}
	writeLibrary := func(t *testing.T, root, content string) {
		require.NoError(t, os.MkdirAll(filepath.Join(root, "usr/lib64"), 0o755))
		require.NoError(t, os.WriteFile(filepath.Join(root, "usr/lib64/libauthselect.so.3.1.1"), []byte(content), 0o755))
	}
	nsswitch := func(t *testing.T, root string) *mqlAuthselectTemplate {
		return authselectTemplateNamed(t, newAuthselect(t, root), "nsswitch.conf")
	}

	t.Run("library merges user-nsswitch.conf", func(t *testing.T) {
		root := setup(t)
		writeLibrary(t, root, "\x00# /etc/authselect/user-nsswitch.conf and run 'authselect apply-changes'.\n\x00")
		tmpl := nsswitch(t, root)
		assert.Contains(t, tmpl.GetContent().Data, "  hosts:    files dns myhostname\n")
		assert.NotContains(t, tmpl.GetContent().Data, "ldap")
		assert.True(t, tmpl.GetIntact().Data)
	})

	t.Run("no library, user-nsswitch.conf present", func(t *testing.T) {
		tmpl := nsswitch(t, setup(t))
		assert.Contains(t, tmpl.GetContent().Data, "hosts:")
		assert.True(t, tmpl.GetIntact().Data)
	})

	t.Run("library without the merge ignores user-nsswitch.conf", func(t *testing.T) {
		root := setup(t)
		writeLibrary(t, root, "\x00/etc/authselect/nsswitch.conf\x00")
		tmpl := nsswitch(t, root)
		assert.NotContains(t, tmpl.GetContent().Data, "hosts:")
		// the generated file holds the merged maps this build would not write
		assert.False(t, tmpl.GetIntact().Data)
	})
}

func TestAuthselectMissingProfile(t *testing.T) {
	root := writeAuthselectHost(t)
	require.NoError(t, os.RemoveAll(filepath.Join(root, "etc/authselect/custom/fixture")))
	a := newAuthselect(t, root)

	assert.False(t, a.GetProfileDir().Data.GetExists().Data)
	templates := a.GetTemplates()
	require.Error(t, templates.Error)
	assert.Equal(t, llx.ErrorKind_ERROR_KIND_NOT_FOUND, llx.KindOf(templates.Error))
	intact := a.GetIntact()
	require.NoError(t, intact.Error)
	assert.False(t, intact.Data)
}

func TestAuthselectProfileLookup(t *testing.T) {
	root := t.TempDir()
	mkdir := func(p string) { require.NoError(t, os.MkdirAll(filepath.Join(root, p), 0o755)) }
	mkdir("/etc/authselect")
	require.NoError(t, os.WriteFile(filepath.Join(root, "etc/authselect/authselect.conf"), []byte("sssd\nwith-faillock\n"), 0o644))
	mkdir("/usr/share/authselect/default/sssd")

	a := newAuthselect(t, root)
	assert.False(t, a.GetIsCustom().Data)
	assert.Equal(t, "/usr/share/authselect/default/sssd", a.GetProfileDir().Data.Path.Data)

	// a vendor profile of the same name takes precedence
	mkdir("/usr/share/authselect/vendor/sssd")
	a = newAuthselect(t, root)
	assert.Equal(t, "/usr/share/authselect/vendor/sssd", a.GetProfileDir().Data.Path.Data)
}
