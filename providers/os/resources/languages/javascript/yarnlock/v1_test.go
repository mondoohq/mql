package yarnlock

import (
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

// yarnV1 is a classic yarn.lock v1 snippet: values are space-separated, `version`
// and `resolved` are quoted but `integrity` is NOT, and there is a nested
// `dependencies:` block. This is the shape the on-the-fly YAML conversion must
// handle (a real `yarn add` lockfile).
const yarnV1 = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


accepts@~1.3.8:
  version "1.3.8"
  resolved "https://registry.yarnpkg.com/accepts/-/accepts-1.3.8.tgz#0bf0be125b67014adcb0b0921e62db7bffe16b2e"
  integrity sha512-PYAthTa2m2VKxuvSD3DPC/Gy+U+sOA1LAuT8mkmRuvw+NACSaeXEQ+NHcVF7rONl6qcaxV3Uuemwawk+7+SJLw==
  dependencies:
    mime-types "~2.1.34"
    negotiator "0.6.3"

negotiator@0.6.3:
  version "0.6.3"
  resolved "https://registry.yarnpkg.com/negotiator/-/negotiator-0.6.3.tgz"
  integrity sha512-+EUsqGPLsM+j/zdChZjsnX51g4XrHFOIXwfnCVPGlQk/k5giakcKsuxCObBRu6DSm9opw/O6slWbJdghQM4bBg==
`

func TestYarnLockV1(t *testing.T) {
	bom, err := (&Extractor{}).Parse(strings.NewReader(yarnV1), "yarn.lock")
	require.NoError(t, err, "classic yarn.lock v1 (unquoted integrity) must parse")

	pkgs := bom.Transitive()
	accepts := pkgs.Find("accepts")
	require.NotNil(t, accepts, "accepts present")
	require.Equal(t, "1.3.8", accepts.Version)

	// integrity → hash
	require.Len(t, accepts.Hashes, 1)
	require.Equal(t, "SHA-512", accepts.Hashes[0].Alg)
	require.NotEmpty(t, accepts.Hashes[0].Value)

	// dependency edge (accepts → negotiator) resolved to a purl
	require.Contains(t, accepts.DependsOn, "pkg:npm/negotiator@0.6.3")
}
