var reMethodName = regexp.MustCompile(`\.[a-z]`)

func capitalizeDot(in []byte) []byte {
	return bytes.ToUpper([]byte{in[1]})
}

func (r *Resource) interfaceName(b *goBuilder) string {
	return resource2goname(r.ID, b)
}

// checkOwnerFilledResourcesArePrivate rejects a public resource that only its
// owner's accessor can populate. A dotted path resolves to the longest matching
// resource name, so while it is public `owner.name.field` builds a bare instance
// that skips the accessor and reads null for every field. Marking it private
// makes the compiler use the accessor instead; see mqlc.prefersFieldOverResource.
func (b *goBuilder) checkOwnerFilledResourcesArePrivate(all []*Resource) {
	byID := make(map[string]*Resource, len(all))
	for _, r := range all {
		byID[r.ID] = r
	}

	for _, r := range all {
		if r.IsPrivate || !b.onlyOwnerCanFill(r) {
			continue
		}

		dot := strings.LastIndex(r.ID, ".")
		if dot == -1 {
			continue
		}
		owner, ok := byID[r.ID[:dot]]
		if !ok {
			continue
		}
		if !b.declaresAccessorFor(owner, r.ID[dot+1:], r.ID) {
			continue
		}

		b.errors.Add(fmt.Errorf(
			"resource %s is public, but only the `%s` accessor on %s can fill it. "+
				"A path like `%s.<field>` therefore compiles to a bare %s and every field reads null. Mark the resource `private`",
			r.ID, r.ID[dot+1:], owner.ID, r.ID, r.ID))
	}
}

// onlyOwnerCanFill reports whether a resource has no way to populate itself:
// every field is data-only and there is no init to build it from args.
func (b *goBuilder) onlyOwnerCanFill(r *Resource) bool {
	if r.Body == nil || r.ListType != nil {
		return false
	}
	if len(r.GetInitFields()) > 0 || b.collector.HasInit(r.interfaceName(b)) {
		return false
	}

	fields := 0
	for _, f := range r.Body.Fields {
		if f.BasicField == nil || f.BasicField.ID == "" {
			continue
		}
		if !f.BasicField.isStatic() {
			return false
		}
		fields++
	}
	return fields > 0
}

// declaresAccessorFor reports whether owner declares `name` as an accessor for
// resourceID. Only fields spelled out in the .lr count: the singular accessors lr
// synthesizes for every `x.y` resource reach nothing.
func (b *goBuilder) declaresAccessorFor(owner *Resource, name string, resourceID string) bool {
	if owner.Body == nil {
		return false
	}
	for _, f := range owner.Body.Fields {
		if f.BasicField == nil || f.BasicField.ID != name {
			continue
		}
		return f.BasicField.Type.Type(b.ast) == types.Resource(resourceID)
	}
	return false
}

var caser = cases.Title(language.English, cases.NoLower)

func resource2goname(s string, b *goBuilder) string {
	pack := strings.SplitN(s, ".", 2)
	var name string
	if pack[0] != s {
		resources, ok := b.ast.imports[pack[0]]
		if ok {
			if _, ok := resources[pack[1]]; !ok {
				b.errors.Add(errors.New("cannot find resource " + pack[1] + " in imported resource pack " + pack[0]))
			}
			name = pack[0] + "." + caser.String(string(
				reMethodName.ReplaceAllFunc([]byte(pack[1]), capitalizeDot),
			))
			b.packsInUse[pack[0]] = struct{}{}
		}
	}
	if name == "" {
		// A dotted name that is not a known pack is normally just a local
		// resource (`os.unix.sshd`). If it is not local either, the first
		// segment was meant as a pack qualifier and the import is missing --
		// which otherwise passes silently and emits types.Resource("core.cpe")
		// for a resource actually called `cpe`.
		if pack[0] != s && !b.ast.hasLocalResource(s) {
			b.errors.Add(errors.New("cannot find resource " + s +
				"; if " + pack[0] + " is another provider, add `import " + pack[0] + "`"))
		}
		name = caser.String(string(
			reMethodName.ReplaceAllFunc([]byte(s), capitalizeDot),
		))
	}

	return name
}

func (b *ResourceDef) staticFields() []*BasicField { //nolint:unused
	res := []*BasicField{}
	for _, f := range b.Fields {
		if f.BasicField != nil {
			if f.BasicField.isStatic() {
				res = append(res, f.BasicField)
			}
		}
	}
	return res
}

func (f *BasicField) goName() string {
	return caser.String(f.ID)
}

func (f *BasicField) isStatic() bool {
	return f.Args == nil
}

func (f *BasicField) methodname() string {
	return caser.String(f.ID)
}

// Retrieve the raw mondoo equivalent type, which can be looked up
// as a resource.
func (t *Type) Type(ast *LR) types.Type {
	if t.SimpleType != nil {
		return t.SimpleType.typeItems(ast)
	}
	if t.ListType != nil {
		return t.ListType.typeItems(ast)
	}
	if t.MapType != nil {
		return t.MapType.typeItems(ast)
	}
	return types.Any
}

func (t *MapType) typeItems(ast *LR) types.Type {
	return types.Map(t.Key.typeItems(ast), t.Value.Type(ast))
}

func (t *ListType) typeItems(ast *LR) types.Type {
	return types.Array(t.Type.Type(ast))
}

func (t *SimpleType) typeItems(ast *LR) types.Type {
	switch t.Type {
	case "bool":
		return types.Bool
	case "int":
		return types.Int
	case "float":
		return types.Float
	case "string":
		return types.String
	case "regex":
		return types.Regex
	case "time":
		return types.Time
	case "dict":
		return types.Dict
	case "version":
		return types.Version
	case "ip":
		return types.IP
	case "range":
		return types.Range
	case "asset":
		return types.Asset
	case "any":
		return types.Any
	default:
		return resourceType(t.Type, ast)
	}
}

// Try to build an MQL resource from the given name. It may or may not exist in
// a pack. If it doesn't exist at all
func resourceType(name string, ast *LR) types.Type {
	pack := strings.SplitN(name, ".", 2)
	if pack[0] != name {
		resources, ok := ast.imports[pack[0]]
		if ok {
			if _, ok := resources[pack[1]]; ok {
				return types.Resource(pack[1])
			}
		}
	}

	// TODO: look up resources in the current registry and notify if they are not found

	return types.Resource(name)
}

// Retrieve the mondoo equivalent of the type. This is a stringified type
// i.e. it can be compiled with the MQL imports
func (t *Type) mondooType(b *goBuilder) string {
	i := t.mondooTypeItems(b)
	if i == "" {
		return "NO_TYPE_DETECTED"
	}
	return i
}

func (t *Type) mondooTypeItems(b *goBuilder) string {
	if t.SimpleType != nil {
		return t.SimpleType.mondooTypeItems(b)
	}
	if t.ListType != nil {
		return t.ListType.mondooTypeItems(b)
	}
	if t.MapType != nil {
		return t.MapType.mondooTypeItems(b)
	}
	return ""
}

func (t *MapType) mondooTypeItems(b *goBuilder) string {
	return "types.Map(" + t.Key.mondooTypeItems(b) + ", " + t.Value.mondooTypeItems(b) + ")"
}

func (t *ListType) mondooTypeItems(b *goBuilder) string {
	return "types.Array(" + t.Type.mondooTypeItems(b) + ")"
}

func (t *SimpleType) mondooTypeItems(b *goBuilder) string {
	switch t.Type {
	case "bool":
		return "types.Bool"
	case "int":
		return "types.Int"
	case "float":
		return "types.Float"
	case "string":
		return "types.String"
	case "regex":
		return "types.Regex"
	case "time":
		return "types.Time"
	case "range":
		return "types.Range"
	case "asset":
		return "types.Asset"
	case "dict":
		return "types.Dict"
	case "version":
		return "types.Version"
	case "ip":
		return "types.IP"
	case "any":
		return "types.Any"
	default:
		if name, ok := b.importName(t.Type); ok {
			return "types.Resource(\"" + name + "\")"
		}
		// A dotted name that is not a known pack is normally a local resource
		// (`os.unix.sshd`). If it is not local either, the leading segment was
		// meant as a pack qualifier and the import is missing. Without this the
		// qualifier silently becomes part of the name, emitting
		// types.Resource("core.cpe") for a resource actually called `cpe`.
		if pack, _, dotted := strings.Cut(t.Type, "."); dotted && !b.ast.hasLocalResource(t.Type) {
			b.errors.Add(errors.New("cannot find resource " + t.Type +
				"; if " + pack + " is another provider, add `import " + pack + "`"))
		}
		return "types.Resource(\"" + t.Type + "\")"
	}
}

func (t *Type) containsResource(b *goBuilder) bool {
	if t.ListType != nil {
		return t.ListType.Type.containsResource(b)
	}
	if t.MapType != nil {
		return t.MapType.Value.containsResource(b)
	}
	if t.SimpleType != nil {
		if _, ok := primitiveTypes[t.SimpleType.Type]; !ok {
			return true
		}
	}
	return false
}

// The go type is the golang-equivalent code type, i.e. the type of the
// actual objects that are being moved around.
func (t *Type) goType(b *goBuilder) string {
	if t.SimpleType != nil {
		return t.SimpleType.goType(b)
	}
	if t.ListType != nil {
		return t.ListType.goType()
	}
	if t.MapType != nil {
		return t.MapType.goType(b)
	}
	return "NO_TYPE_DETECTED"
}

func (t *MapType) goType(b *goBuilder) string {
	// limited to any because we cannot cast as universally
	// between types yet
	return "map[" + t.Key.goType(b) + "]any"
}

func (t *ListType) goType() string {
	// limited to []any because we cannot cast as universally
	// between types yet
	return "[]any"
}

var primitiveTypes = map[string]string{
	"string":  "string",
	"bool":    "bool",
	"int":     "int64",
	"float":   "float64",
	"time":    "*time.Time",
	"range":   "llx.Range",
	"regex":   "string",
	"dict":    "any",
	"version": "string",
	"ip":      "llx.RawIP",
	"asset":   "*llx.AssetValue",
	"any":     "any",
}

func (t *SimpleType) goType(b *goBuilder) string {
	pt, ok := primitiveTypes[t.Type]
	if ok {
		return pt
	}

	if _, ok := b.importName(t.Type); ok {
		return "plugin.Resource"
	}

	return "*mql" + resource2goname(t.Type, b)
}

func (t *Type) goZeroValue() string {
	if t.SimpleType != nil {
		return t.SimpleType.goZeroValue()
	}
	return "nil"
}

