func (b *goBuilder) importName(symbol string) (string, bool) {
	parts := strings.SplitN(symbol, ".", 2)
	if len(parts) >= 2 {
		if ref, ok := b.ast.imports[parts[0]]; ok {
			if _, ok := ref[parts[1]]; ok {
				return parts[1], true
			}
		}
	}
	return "", false
}

func indent(s string, depth int) string { //nolint:unused
	space := ""
	for i := 0; i < depth; i++ {
		space += "\t"
	}
	return space + strings.ReplaceAll(s, "\n", "\n"+space)
}

