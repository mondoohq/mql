func TestCache_NeverCarriesAcceptance(t *testing.T) {
	// Synthetic. A warm cache must not let one call's acceptance answer
	// another's: verify under an accepting policy, then under the empty
	// policy, and the second call must not read verified.
	s := newTestSigstore(t)
	artifact := []byte("artifact")
	digest := "sha256:" + sha256Hex(artifact)
	sg := s.keyless(githubIdentity("acme/app", ".github/workflows/release.yml", "refs/heads/main"))
	b := s.dsseBundle(sg, statementJSON(t, "https://example.test/p", map[string]any{}, sha256Hex(artifact)), bundleOpts{})
	cache := NewCache()
	accept, err := ParseSigners("github-actions:acme/app")
	require.NoError(t, err)

	r1, err := VerifyBlob(context.Background(), digest, b, accept, WithTrustRoot(s.trust), WithCache(cache))
	require.NoError(t, err)
	require.True(t, r1.Verified, r1.Reason)

	r2, err := VerifyBlob(context.Background(), digest, b, Policy{}, WithTrustRoot(s.trust), WithCache(cache))
	require.NoError(t, err)
	assert.True(t, r2.SignatureValid, "validity is cached")
	assert.False(t, r2.Accepted)
	assert.False(t, r2.Verified, "acceptance is not carried by the cache")
	assert.Len(t, cache.m, 1, "the second call was served from the cache")

	other, err := ParseSigners("github-actions:other/*")
	require.NoError(t, err)
	r3, err := VerifyBlob(context.Background(), digest, b, other, WithTrustRoot(s.trust), WithCache(cache))
	require.NoError(t, err)
	assert.False(t, r3.Verified)
}

// caGenerateRoot is a root CA no trust root trusts.
func caGenerateRoot() (*x509.Certificate, *ecdsa.PrivateKey, error) {
	return ca.GenerateRootCa()
}

// replaceB64 replaces, in a protojson bundle, the base64 of old by that of
// new.
func replaceB64(t *testing.T, b, old, new []byte) []byte {
	o := base64.StdEncoding.EncodeToString(old)
	n := base64.StdEncoding.EncodeToString(new)
	out := strings.Replace(string(b), o, n, 1)
	require.NotEqual(t, string(b), out, "the payload was not found in the bundle")
	return []byte(out)
}

