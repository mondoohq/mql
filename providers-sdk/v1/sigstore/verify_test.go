// Every fixture in this package is synthetic: keys, certificate authorities,
// transparency-log entries and bundles are generated by the test, because a
// test cannot reach the public Sigstore instance. The layouts follow cosign's
// annotations and the Sigstore bundle format; the transparency log is
// sigstore-go's own test log (pkg/testing/ca), so entries, signed entry
// timestamps and inclusion proofs are the ones its verifier reads.

// Fulcio certificate extensions, as Fulcio issues them.
var (
	oidIssuerV2      = asn1.ObjectIdentifier{1, 3, 6, 1, 4, 1, 57264, 1, 8}
	oidBuildSigner   = asn1.ObjectIdentifier{1, 3, 6, 1, 4, 1, 57264, 1, 9}
	oidSourceRepoURI = asn1.ObjectIdentifier{1, 3, 6, 1, 4, 1, 57264, 1, 12}
)

// testSigstore is a certificate authority and a transparency log made for one
// test, and the trust root that trusts them.
type testSigstore struct {
	t        *testing.T
	vs       *ca.VirtualSigstore
	root     *x509.Certificate
	inter    *x509.Certificate
	interKey *ecdsa.PrivateKey
	logID    string
	trust    *TrustRoot
	rootJSON []byte
	now      time.Time
}

func newTestSigstore(t *testing.T) *testSigstore {
	t.Helper()
	vs, err := ca.NewVirtualSigstore()
	require.NoError(t, err)
	s := &testSigstore{t: t, vs: vs, now: time.Now().Truncate(time.Second)}
	rootCert, rootKey, err := ca.GenerateRootCa()
	require.NoError(t, err)
	inter, interKey, err := ca.GenerateFulcioIntermediate(rootCert, rootKey)
	require.NoError(t, err)
	s.root, s.inter, s.interKey = rootCert, inter, interKey
	logs := vs.RekorLogs()
	for id, l := range logs {
		s.logID = id
		// The log id is the raw sha256 of the log key, as a real trusted
		// root carries it, so the root survives a JSON round trip.
		raw, err := hex.DecodeString(id)
		require.NoError(t, err)
		l.ID = raw
	}
	cas := []root.CertificateAuthority{&root.FulcioCertificateAuthority{
		Root: rootCert, Intermediates: []*x509.Certificate{inter},
		ValidityPeriodStart: s.now.Add(-24 * time.Hour), ValidityPeriodEnd: s.now.Add(24 * time.Hour),
		URI: "https://fulcio.test.invalid",
	}}
	tr, err := root.NewTrustedRoot(root.TrustedRootMediaType01, cas, nil, vs.TimestampingAuthorities(), logs)
	require.NoError(t, err)
	s.rootJSON, err = tr.MarshalJSON()
	require.NoError(t, err)
	s.trust = NewTrustRoot(tr, TrustPrivate, sha(s.rootJSON))
	return s
}

// identity is what a keyless certificate names.
type identity struct {
	SAN, Issuer, SourceRepo, BuildSigner string
}

func githubIdentity(repo, workflow, ref string) identity {
	san := "https://github.com/" + repo + "/" + workflow + "@" + ref
	return identity{SAN: san, Issuer: GitHubActionsIssuer, SourceRepo: "https://github.com/" + repo, BuildSigner: san}
}

// testSigner signs: a keyless certificate and its key, or a bare key.
type testSigner struct {
	key  *ecdsa.PrivateKey
	cert *x509.Certificate
}

func (s testSigner) verifierPEM(t *testing.T) []byte {
	if s.cert != nil {
		return pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: s.cert.Raw})
	}
	der, err := x509.MarshalPKIXPublicKey(&s.key.PublicKey)
	require.NoError(t, err)
	return pem.EncodeToMemory(&pem.Block{Type: "PUBLIC KEY", Bytes: der})
}

func (s testSigner) fingerprint(t *testing.T) string {
	der, err := x509.MarshalPKIXPublicKey(&s.key.PublicKey)
	require.NoError(t, err)
	return Fingerprint(der)
}

func newKeySigner(t *testing.T) testSigner {
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	require.NoError(t, err)
	return testSigner{key: key}
}

// keyless issues a Fulcio-style certificate for id from the test CA (or from
// another CA when other is set, for an untrusted chain).
func (s *testSigstore) keyless(id identity) testSigner {
	return s.keylessFrom(s.inter, s.interKey, id)
}

func (s *testSigstore) keylessFrom(parent *x509.Certificate, parentKey *ecdsa.PrivateKey, id identity) testSigner {
	t := s.t
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	require.NoError(t, err)
	tmpl := &x509.Certificate{
		SerialNumber: big.NewInt(time.Now().UnixNano()),
		NotBefore:    s.now.Add(-time.Minute), NotAfter: s.now.Add(10 * time.Minute),
		KeyUsage:    x509.KeyUsageDigitalSignature,
		ExtKeyUsage: []x509.ExtKeyUsage{x509.ExtKeyUsageCodeSigning},
	}
	if u, err := url.Parse(id.SAN); err == nil && u.Scheme != "" {
		tmpl.URIs = []*url.URL{u}
	} else {
		tmpl.EmailAddresses = []string{id.SAN}
	}
	for oid, v := range map[string]string{oidIssuerV2.String(): id.Issuer, oidBuildSigner.String(): id.BuildSigner, oidSourceRepoURI.String(): id.SourceRepo} {
		if v == "" {
			continue
		}
		val, err := asn1.MarshalWithParams(v, "utf8")
		require.NoError(t, err)
		var o asn1.ObjectIdentifier
		switch oid {
		case oidIssuerV2.String():
			o = oidIssuerV2
		case oidBuildSigner.String():
			o = oidBuildSigner
		default:
			o = oidSourceRepoURI
		}
		tmpl.ExtraExtensions = append(tmpl.ExtraExtensions, pkix.Extension{Id: o, Value: val})
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, parent, &key.PublicKey, parentKey)
	require.NoError(t, err)
	cert, err := x509.ParseCertificate(der)
	require.NoError(t, err)
	return testSigner{key: key, cert: cert}
}

// rekorBody is the canonical Rekor v1 entry of a signature: dsse for an
// envelope, hashedrekord for a message.
func (s *testSigstore) rekorBody(kind string, artifact []byte, sig []byte, verifier []byte) []byte {
	props := rekortypes.ArtifactProperties{PublicKeyBytes: [][]byte{verifier}, PKIFormat: string(pki.X509), SignatureBytes: sig}
	version := "0.0.1"
	if kind == "hashedrekord" {
		sum := sha256.Sum256(artifact)
		props.ArtifactHash = hex.EncodeToString(sum[:])
	} else {
		props.ArtifactBytes = artifact
	}
	ctx := context.Background()
	pe, err := rekortypes.NewProposedEntry(ctx, kind, version, props)
	require.NoError(s.t, err)
	impl, err := rekortypes.CreateVersionedEntry(pe)
	require.NoError(s.t, err)
	body, err := rekortypes.CanonicalizeEntry(ctx, impl)
	require.NoError(s.t, err)
	return body
}

// logEntry logs body at the given time; withProof adds an inclusion proof,
// which a bundle of version 0.2 and later needs.
func (s *testSigstore) logEntry(body []byte, at time.Time, withProof bool) *protorekor.TransparencyLogEntry {
	t := s.t
	set, err := s.vs.RekorSignPayload(tlog.RekorPayload{
		Body: base64.StdEncoding.EncodeToString(body), IntegratedTime: at.Unix(), LogIndex: 0, LogID: s.logID,
	})
	require.NoError(t, err)
	logIDRaw, err := hex.DecodeString(s.logID)
	require.NoError(t, err)
	var kv struct{ Kind, APIVersion string }
	require.NoError(t, json.Unmarshal(body, &kv))
	tle := &protorekor.TransparencyLogEntry{
		LogIndex:          0,
		LogId:             &protocommon.LogId{KeyId: logIDRaw},
		KindVersion:       &protorekor.KindVersion{Kind: kv.Kind, Version: kv.APIVersion},
		IntegratedTime:    at.Unix(),
		InclusionPromise:  &protorekor.InclusionPromise{SignedEntryTimestamp: set},
		CanonicalizedBody: body,
	}
	if withProof {
		p, err := s.vs.GetInclusionProof(body)
		require.NoError(t, err)
		rootHash, err := hex.DecodeString(*p.RootHash)
		require.NoError(t, err)
		ip := &protorekor.InclusionProof{LogIndex: *p.LogIndex, RootHash: rootHash, TreeSize: *p.TreeSize,
			Checkpoint: &protorekor.Checkpoint{Envelope: *p.Checkpoint}}
		for _, h := range p.Hashes {
			hb, err := hex.DecodeString(h)
			require.NoError(t, err)
			ip.Hashes = append(ip.Hashes, hb)
		}
		tle.InclusionProof = ip
	}
	return tle
}

// signDSSE signs payload as a DSSE envelope.
func signDSSE(t *testing.T, key crypto.Signer, payloadType string, payload []byte) (*dsse.Envelope, []byte) {
	pae := dsse.PAE(payloadType, payload)
	sum := sha256.Sum256(pae)
	sig, err := key.Sign(rand.Reader, sum[:], crypto.SHA256)
	require.NoError(t, err)
	return &dsse.Envelope{
		PayloadType: payloadType,
		Payload:     base64.StdEncoding.EncodeToString(payload),
		Signatures:  []dsse.Signature{{Sig: base64.StdEncoding.EncodeToString(sig)}},
	}, sig
}

// signMessage signs artifact's sha256.
func signMessage(t *testing.T, key crypto.Signer, artifact []byte) []byte {
	sum := sha256.Sum256(artifact)
	sig, err := key.Sign(rand.Reader, sum[:], crypto.SHA256)
	require.NoError(t, err)
	return sig
}

const inTotoPayloadType = "application/vnd.in-toto+json"

// statementJSON is an in-toto statement over the given sha256 digests.
func statementJSON(t *testing.T, predicateType string, predicate any, digests ...string) []byte {
	var subjects []map[string]any
	for i, d := range digests {
		subjects = append(subjects, map[string]any{"name": fmt.Sprintf("subject-%d", i), "digest": map[string]string{"sha256": d}})
	}
	b, err := json.Marshal(map[string]any{
		"_type": "https://in-toto.io/Statement/v1", "subject": subjects,
		"predicateType": predicateType, "predicate": predicate,
	})
	require.NoError(t, err)
	return b
}

// bundleOpts shape a test bundle.
type bundleOpts struct {
	noLog   bool
	logAt   time.Time
	keyHint string
}

// dsseBundle is a Sigstore bundle v0.3 of a DSSE envelope over payload.
func (s *testSigstore) dsseBundle(sg testSigner, payload []byte, o bundleOpts) []byte {
	t := s.t
	env, sig := signDSSE(t, sg.key, inTotoPayloadType, payload)
	vm := &protobundle.VerificationMaterial{}
	if sg.cert != nil {
		vm.Content = &protobundle.VerificationMaterial_Certificate{Certificate: &protocommon.X509Certificate{RawBytes: sg.cert.Raw}}
	} else {
		hint := o.keyHint
		if hint == "" {
			hint = sg.fingerprint(t)
		}
		vm.Content = &protobundle.VerificationMaterial_PublicKey{PublicKey: &protocommon.PublicKeyIdentifier{Hint: hint}}
	}
	if !o.noLog {
		envJSON, err := json.Marshal(env)
		require.NoError(t, err)
		at := o.logAt
		if at.IsZero() {
			at = s.now
		}
		vm.TlogEntries = []*protorekor.TransparencyLogEntry{s.logEntry(s.rekorBody("dsse", envJSON, sig, sg.verifierPEM(t)), at, true)}
	}
	pb := &protobundle.Bundle{
		MediaType:            "application/vnd.dev.sigstore.bundle.v0.3+json",
		VerificationMaterial: vm,
		Content: &protobundle.Bundle_DsseEnvelope{DsseEnvelope: &protodsse.Envelope{
			Payload: payload, PayloadType: inTotoPayloadType,
			Signatures: []*protodsse.Signature{{Sig: sig}},
		}},
	}
	b, err := protojson.Marshal(pb)
	require.NoError(t, err)
	return b
}

// messageBundle is a Sigstore bundle v0.3 of a message signature over
// artifact.
func (s *testSigstore) messageBundle(sg testSigner, artifact []byte) []byte {
	t := s.t
	sig := signMessage(t, sg.key, artifact)
	sum := sha256.Sum256(artifact)
	vm := &protobundle.VerificationMaterial{
		Content:     &protobundle.VerificationMaterial_Certificate{Certificate: &protocommon.X509Certificate{RawBytes: sg.cert.Raw}},
		TlogEntries: []*protorekor.TransparencyLogEntry{s.logEntry(s.rekorBody("hashedrekord", artifact, sig, sg.verifierPEM(t)), s.now, true)},
	}
	pb := &protobundle.Bundle{
		MediaType:            "application/vnd.dev.sigstore.bundle.v0.3+json",
		VerificationMaterial: vm,
		Content: &protobundle.Bundle_MessageSignature{MessageSignature: &protocommon.MessageSignature{
			MessageDigest: &protocommon.HashOutput{Algorithm: protocommon.HashAlgorithm_SHA2_256, Digest: sum[:]},
			Signature:     sig,
		}},
	}
	b, err := protojson.Marshal(pb)
	require.NoError(t, err)
	return b
}

// cosignLayer is a cosign .att layer (a DSSE envelope) or .sig layer (a
// simple-signing payload) with the annotations cosign writes.
func (s *testSigstore) cosignLayer(sg testSigner, env Envelope, payload []byte, logged bool) ([]byte, map[string]string) {
	t := s.t
	ann := map[string]string{}
	var blob, sig []byte
	var kind string
	var loggedArtifact []byte
	switch env {
	case EnvelopeCosignAttestation:
		e, sg2 := signDSSE(t, sg.key, inTotoPayloadType, payload)
		var err error
		blob, err = json.Marshal(e)
		require.NoError(t, err)
		sig, kind, loggedArtifact = sg2, "dsse", blob
		ann["predicateType"] = "https://spdx.dev/Document"
	case EnvelopeCosignSignature:
		sig = signMessage(t, sg.key, payload)
		blob, kind, loggedArtifact = payload, "hashedrekord", payload
		ann[cosignSignatureAnnotation] = base64.StdEncoding.EncodeToString(sig)
	}
	if sg.cert != nil {
		ann[cosignCertAnnotation] = string(sg.verifierPEM(t))
		ann[cosignChainAnnotation] = string(pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: s.inter.Raw})) +
			string(pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: s.root.Raw}))
	}
	if logged {
		body := s.rekorBody(kind, loggedArtifact, sig, sg.verifierPEM(t))
		tle := s.logEntry(body, s.now, false)
		ra := map[string]any{
			"SignedEntryTimestamp": base64.StdEncoding.EncodeToString(tle.InclusionPromise.SignedEntryTimestamp),
			"Payload": map[string]any{
				"body": base64.StdEncoding.EncodeToString(body), "integratedTime": tle.IntegratedTime,
				"logIndex": tle.LogIndex, "logID": s.logID,
			},
		}
		b, err := json.Marshal(ra)
		require.NoError(t, err)
		ann[cosignBundleAnnotation] = string(b)
	}
	return blob, ann
}

func sha256Hex(b []byte) string {
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}

