func TestDescribeProvenance_SLSAv1(t *testing.T) {
	// Synthetic: the field layout of SLSA provenance v1 as GitHub's
	// attest-build-provenance writes it; values invented.
	r := Result{Payload: statementJSON(t, "https://slsa.dev/provenance/v1", map[string]any{
		"buildDefinition": map[string]any{
			"buildType":          "https://actions.github.io/buildtypes/workflow/v1",
			"externalParameters": map[string]any{"workflow": map[string]any{"repository": "https://github.com/acme/app"}},
			"resolvedDependencies": []any{
				map[string]any{"uri": "git+https://github.com/acme/app@refs/heads/main", "digest": map[string]string{"gitCommit": "0123abc"}},
			},
		},
		"runDetails": map[string]any{"builder": map[string]any{"id": "https://github.com/actions/runner/github-hosted"}},
	}, sha256Hex([]byte("img")))}
	describePayload(&r)
	assert.Equal(t, "https://slsa.dev/provenance/v1", r.PredicateType)
	assert.Equal(t, []string{"sha256:" + sha256Hex([]byte("img"))}, r.SubjectDigests)
	assert.Equal(t, "https://github.com/actions/runner/github-hosted", r.BuilderID)
	assert.Equal(t, "https://github.com/acme/app", r.SourceRepository)
	assert.Equal(t, "0123abc", r.SourceRevision)
	require.Len(t, r.Materials, 1)
	assert.Equal(t, 0, r.SLSABuildLevel, "provenance states no level")
}

